def check_already_greeted(recent_history: str, user_name: str) -> bool:
    """Перевіряє, чи у нещодавній історії чату вже спілкувалися Бугайчик та даний користувач"""
    if not recent_history or not user_name:
        return False
    lines = [l for l in recent_history.splitlines() if l.strip()][-12:]
    has_bugaichyk = any("Бугайчик" in l for l in lines)
    has_user = any(user_name in l for l in lines)
    return has_bugaichyk or has_user

