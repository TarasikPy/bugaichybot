    prompt = BUGAICHYK_SYSTEM_PROMPT
    if user_name:
        name_lower = user_name.lower()
        is_girl = any(g in name_lower for g in ["ангел", "мяу", "веронік", "маргарит", "рита", "марія", "адріан", "алін", "анік", "alina", "аб/марія"])
        is_guy = any(b in name_lower for b in ["кійотак", "арма", "влад", "сергій", "тарас", "яросл", "лук'ян", "андрій"])

        if is_girl:
            gender_instr = (
                f"ПОТОЧНИЙ СПІВРОЗМОВНИК: {user_name} (ДІВЧИНА/ПАННА).\n"
                "ТВОЯ ПОВЕДІНКА: Будь з нею харизматичним, елегантним кавалєром та галантним карпатським газдою! "
                "Звертайся 'панно', 'квітонько', 'красуне', 'мої шанування'. Роби дотепні й вишукані компліменти з бойківським колоритом, підколюй ніжно й саркастично-елегантно."
            )
        elif is_guy:
            gender_instr = (
                f"ПОТОЧНИЙ СПІВРОЗМОВНИК: {user_name} (ХЛОПЕЦЬ/КОЛЕГА).\n"
                "ТВОЯ ПОВЕДІНКА: Будь з ним гострим, саркастичним карпатським газдою! "
                "Влучно підйобуй його по лору (наприклад, кодинг, Python, підвальна качалка, техніка, філософія), стьобайся з перцем та чоловічим сарказмом! "
                "Навіть на звичайне 'привіт' чи звернення відповідай колоритно відповідно до лору (наприклад, 'Здоров був, кодер!', 'Дай Боже, карпатський хастлере!', 'Здоров, підвальний качок!')."
            )
        else:
            gender_instr = f"ПОТОЧНИЙ СПІВРОЗМОВНИК: {user_name}. Реагуй відповідно до його/її лору та локації!"

