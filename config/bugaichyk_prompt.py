def get_bugaichyk_prompt_for_user(user_name: str = "", user_id: int = None) -> str:
    """Генерує розширений системний промпт для Бугайчика з врахуванням контексту користувача"""
    prompt = BUGAICHYK_SYSTEM_PROMPT
    if user_name:
        prompt += f"\nПоточний співрозмовник: {user_name} (ID: {user_id or '—'}). Реагуй відповідно до його/її лору та локації!\n"
